-- Tests for the incident response core and the vector store.
-- Run:  psql "$DATABASE_URL" -f db/tests/00_test_helpers.sql -f db/tests/01_core_tests.sql
-- Everything runs inside one transaction and is rolled back at the end.

\set ON_ERROR_STOP on
\set QUIET on
\o /dev/null
BEGIN;

-- Fixtures: one admin, two analysts, one viewer, two assets, two playbooks
INSERT INTO users (full_name, email, password_hash, role_id) VALUES
    ('Test Admin',     't.admin@cirt.test',    crypt('Adm1n!pass', gen_salt('bf', 10)), 1),
    ('Test Analyst A', 't.analyst.a@cirt.test', crypt('An4lyst!a',  gen_salt('bf', 10)), 2),
    ('Test Analyst B', 't.analyst.b@cirt.test', crypt('An4lyst!b',  gen_salt('bf', 10)), 2),
    ('Test Viewer',    't.viewer@cirt.test',    crypt('V1ewer!pw',  gen_salt('bf', 10)), 3);

INSERT INTO assets (hostname, ip_address, asset_type, operating_system, department, criticality, is_internet_facing) VALUES
    ('mail-gw-01.corp.test', '10.20.0.5', 'SERVER',      'Ubuntu 22.04', 'IT Infrastructure', 5, TRUE),
    ('fin-ws-114.corp.test', '10.40.1.114', 'WORKSTATION', 'Windows 11',   'Finance',           3, FALSE);

INSERT INTO playbooks (name, category, description, created_by)
SELECT 'Phishing response (test)', 'PHISHING', 'Contain and clean up a credential phishing campaign', user_id
FROM users WHERE email = 't.admin@cirt.test';

INSERT INTO playbook_steps (playbook_id, step_no, title, instructions, expected_minutes)
SELECT p.playbook_id, s.step_no, s.title, s.instr, s.mins
FROM playbooks p,
     (VALUES (1, 'Quarantine the email',     'Pull the message from all mailboxes',            15),
             (2, 'Block sender and URLs',     'Add sender domain and links to the mail gateway', 20),
             (3, 'Reset exposed credentials', 'Force reset for every user who clicked',          60)) AS s(step_no, title, instr, mins)
WHERE p.name = 'Phishing response (test)';

INSERT INTO playbooks (name, category, description)
VALUES ('Ransomware containment (test)', 'RANSOMWARE', 'Isolate hosts and preserve evidence');
INSERT INTO playbook_steps (playbook_id, step_no, title, instructions, expected_minutes)
SELECT playbook_id, 1, 'Isolate host', 'Disconnect affected hosts from the network', 10
FROM playbooks WHERE name = 'Ransomware containment (test)';

-- Act as the admin for everything that follows
SELECT set_config('app.current_user_id', user_id::TEXT, true) FROM users WHERE email = 't.admin@cirt.test' \gset

\echo '--- Users and roles'
SELECT pg_temp.expect_error(
    $$INSERT INTO users (full_name, email, password_hash, role_id)
      VALUES ('Bad Email', 'not-an-email', crypt('x', gen_salt('bf')), 2)$$,
    'U1 invalid email is rejected');
SELECT pg_temp.expect_error(
    $$INSERT INTO users (full_name, email, password_hash, role_id)
      VALUES ('Plain Text', 'plain@cirt.test', 'password123', 2)$$,
    'U2 plain-text password is rejected');
SELECT pg_temp.expect_error(
    $$INSERT INTO users (full_name, email, password_hash, role_id)
      VALUES ('Dup', 'T.ADMIN@cirt.test', crypt('x', gen_salt('bf')), 2)$$,
    'U3 duplicate email (different case) is rejected');
SELECT pg_temp.expect_error(
    $$INSERT INTO users (full_name, email, password_hash, role_id)
      VALUES ('No Role', 'norole@cirt.test', crypt('x', gen_salt('bf')), 9)$$,
    'U4 unknown role is rejected by FK');

\echo '--- Incident creation and SLA'
INSERT INTO incidents (title, description, category, severity, reported_by, detected_at)
SELECT 'Credential phishing wave targeting finance',
       'Several finance users received a fake Microsoft 365 login page link from a look-alike domain.',
       'PHISHING', 'HIGH', user_id, now() - INTERVAL '20 minutes'
FROM users WHERE email = 't.admin@cirt.test'
RETURNING incident_id AS phish_id \gset

SELECT pg_temp.check(
    (SELECT reference_code ~ '^INC-[0-9]{4}-[0-9]{6}$' FROM incidents WHERE incident_id = :phish_id),
    'I1 reference code generated by trigger');
SELECT pg_temp.check(
    (SELECT resolve_by - created_at = INTERVAL '24 hours' AND respond_by - created_at = INTERVAL '1 hour'
     FROM incidents WHERE incident_id = :phish_id),
    'I2 HIGH severity gets 1h respond / 24h resolve deadlines');
SELECT pg_temp.check(
    (SELECT count(*) = 1 FROM incident_status_history WHERE incident_id = :phish_id AND new_status = 'NEW'),
    'I3 initial status written to history');
SELECT pg_temp.expect_error(
    $$INSERT INTO incidents (title, description, category, severity, reported_by, detected_at, status)
      SELECT 'Skipping the workflow', 'Trying to insert an incident that is already resolved.',
             'MALWARE', 'LOW', user_id, now(), 'RESOLVED' FROM users LIMIT 1$$,
    'I4 incident cannot be created in a non-NEW status');
SELECT pg_temp.expect_error(
    $$INSERT INTO incidents (title, description, category, severity, reported_by, detected_at)
      SELECT 'Future dated', 'Detection time far in the future should not be accepted.',
             'MALWARE', 'LOW', user_id, now() + INTERVAL '2 days' FROM users LIMIT 1$$,
    'I5 detection time in the future is rejected');
SELECT pg_temp.expect_error(
    $$INSERT INTO incidents (title, description, category, severity, reported_by, detected_at)
      SELECT 'Hi', 'Too short title.', 'MALWARE', 'LOW', user_id, now() FROM users LIMIT 1$$,
    'I6 too-short title and description are rejected');

\echo '--- Status workflow'
SELECT pg_temp.expect_error(
    format('UPDATE incidents SET status = %L WHERE incident_id = %s', 'RESOLVED', :phish_id),
    'W1 NEW -> RESOLVED is not an allowed transition');
SELECT pg_temp.expect_error(
    format($$UPDATE incidents SET assigned_to = (SELECT user_id FROM users WHERE email = 't.viewer@cirt.test')
             WHERE incident_id = %s$$, :phish_id),
    'W2 a VIEWER cannot be assigned an incident');

-- give analyst A an existing CRITICAL load so the picker chooses analyst B
INSERT INTO incidents (title, description, category, severity, reported_by, assigned_to, detected_at)
SELECT 'Ransomware note on finance file share',
       'Files on the finance share renamed with .lockbit extension and ransom note dropped.',
       'RANSOMWARE', 'CRITICAL', a.user_id, b.user_id, now() - INTERVAL '5 minutes'
FROM users a, users b
WHERE a.email = 't.admin@cirt.test' AND b.email = 't.analyst.a@cirt.test'
RETURNING incident_id AS ransom_id \gset

CALL sp_assign_incident(:phish_id, NULL);
SELECT pg_temp.check(
    (SELECT u.email = 't.analyst.b@cirt.test' FROM incidents i JOIN users u ON u.user_id = i.assigned_to
     WHERE i.incident_id = :phish_id),
    'W3 sp_assign_incident picks the least-loaded analyst');

\echo '--- Playbooks (stored procedure, transaction)'
SELECT playbook_id AS ransom_pb FROM playbooks WHERE name = 'Ransomware containment (test)' \gset
SELECT playbook_id AS phish_pb  FROM playbooks WHERE name = 'Phishing response (test)' \gset
SELECT pg_temp.expect_error(
    format('CALL sp_apply_playbook(%s, %s)', :phish_id, :ransom_pb),
    'P1 playbook for a different category is rejected');

CALL sp_apply_playbook(:phish_id, :phish_pb);

SELECT pg_temp.check(
    (SELECT count(*) = 3 FROM incident_tasks WHERE incident_id = :phish_id),
    'P2 three tasks created from three playbook steps');
SELECT pg_temp.check(
    (SELECT status = 'TRIAGED' AND first_response_at IS NOT NULL FROM incidents WHERE incident_id = :phish_id),
    'P3 incident moved NEW -> TRIAGED and first response time recorded');
SELECT pg_temp.check(
    (SELECT max(due_at) - min(due_at) = INTERVAL '80 minutes' FROM incident_tasks WHERE incident_id = :phish_id),
    'P4 task due times are cumulative (15, 35, 95 minutes)');
SELECT pg_temp.check(
    (SELECT bool_and(t.assigned_to = i.assigned_to)
     FROM incident_tasks t JOIN incidents i USING (incident_id) WHERE incident_id = :phish_id),
    'P5 tasks inherit the incident owner');
SELECT pg_temp.expect_error(
    format('CALL sp_apply_playbook(%s, %s)', :phish_id, :phish_pb),
    'P6 applying the same playbook twice is rejected');
SELECT pg_temp.check(
    (SELECT count(*) = 3 FROM incident_tasks WHERE incident_id = :phish_id),
    'P7 failed call left no partial tasks behind');

\echo '--- Resolution rules'
UPDATE incidents SET status = 'IN_PROGRESS' WHERE incident_id = :phish_id;
SELECT pg_temp.expect_error(
    format($$UPDATE incidents SET status = 'RESOLVED', resolution_summary = 'Blocked domain and reset passwords'
             WHERE incident_id = %s$$, :phish_id),
    'R1 cannot resolve while tasks are still open');

UPDATE incident_tasks SET status = 'DONE' WHERE incident_id = :phish_id;
SELECT pg_temp.check(
    (SELECT bool_and(completed_at IS NOT NULL) FROM incident_tasks WHERE incident_id = :phish_id),
    'R2 completed_at stamped by trigger when tasks are done');
SELECT pg_temp.expect_error(
    format($$UPDATE incidents SET status = 'RESOLVED' WHERE incident_id = %s$$, :phish_id),
    'R3 resolution summary is required to resolve');

SELECT set_config('app.status_note', 'All clicked users reset, domain blocked at gateway', true) \gset
UPDATE incidents
SET status = 'RESOLVED',
    resolution_summary = 'Look-alike domain blocked at the mail gateway and all 6 affected passwords reset.'
WHERE incident_id = :phish_id;
SELECT set_config('app.status_note', '', true) \gset

SELECT pg_temp.check(
    (SELECT resolved_at IS NOT NULL FROM incidents WHERE incident_id = :phish_id),
    'R4 resolved_at stamped by trigger');
SELECT pg_temp.check(
    (SELECT array_agg(new_status::TEXT ORDER BY history_id) = ARRAY['NEW', 'TRIAGED', 'IN_PROGRESS', 'RESOLVED']
     FROM incident_status_history WHERE incident_id = :phish_id),
    'R5 full status history recorded in order');
SELECT pg_temp.check(
    (SELECT note IS NOT NULL FROM incident_status_history
     WHERE incident_id = :phish_id AND new_status = 'RESOLVED'),
    'R6 status note carried into history');
SELECT pg_temp.check(
    (SELECT sla_state = 'MET' FROM v_incident_overview WHERE incident_id = :phish_id),
    'R7 view reports SLA as MET');

UPDATE incidents SET status = 'IN_PROGRESS' WHERE incident_id = :phish_id;
SELECT pg_temp.check(
    (SELECT resolved_at IS NULL FROM incidents WHERE incident_id = :phish_id),
    'R8 reopening clears resolved_at');

\echo '--- Escalation'
SELECT resolve_by AS old_resolve_by FROM incidents WHERE incident_id = :phish_id \gset
UPDATE incidents SET severity = 'CRITICAL' WHERE incident_id = :phish_id;
SELECT pg_temp.check(
    (SELECT resolve_by < :'old_resolve_by'::TIMESTAMPTZ FROM incidents WHERE incident_id = :phish_id),
    'E1 escalating to CRITICAL pulls the resolve deadline in');

\echo '--- Audit'
SELECT pg_temp.check(
    (SELECT count(*) > 0 FROM audit_log WHERE table_name = 'incidents' AND record_id = :'phish_id'),
    'A1 incident changes written to audit log');
SELECT pg_temp.check(
    NOT EXISTS (SELECT 1 FROM audit_log WHERE table_name = 'users' AND new_data ? 'password_hash'),
    'A2 password hashes never copied into the audit log');
SELECT pg_temp.check(
    (SELECT bool_and(actor_id IS NOT NULL) FROM audit_log WHERE table_name = 'incident_tasks'),
    'A3 audit rows record the acting user');

\echo '--- Views'
SELECT pg_temp.check(
    (SELECT open_incidents = 1 AND open_critical = 1 FROM v_analyst_workload w
     JOIN users u USING (user_id) WHERE u.email = 't.analyst.a@cirt.test'),
    'V1 workload view counts open critical incidents per analyst');
SELECT pg_temp.check(
    (SELECT count(*) >= 2 FROM v_incident_monthly_stats),
    'V2 monthly stats view returns one row per month/category');

\echo '--- Vector similarity'
INSERT INTO incident_embeddings (incident_id, embedding, model_name, content_hash) VALUES
    (:phish_id,  pg_temp.test_vec(0.10),       'test', encode(sha256('a'), 'hex')),
    (:ransom_id, pg_temp.test_vec(0.10, 0.05), 'test', encode(sha256('b'), 'hex'));

INSERT INTO incidents (title, description, category, severity, reported_by, detected_at)
SELECT 'Port scan from external host',
       'Perimeter firewall logged a full TCP port sweep against the DMZ range.',
       'OTHER', 'LOW', user_id, now()
FROM users WHERE email = 't.admin@cirt.test'
RETURNING incident_id AS scan_id \gset
INSERT INTO incident_embeddings (incident_id, embedding, model_name, content_hash)
VALUES (:scan_id, pg_temp.test_vec(2.30), 'test', encode(sha256('c'), 'hex'));

SELECT pg_temp.check(
    (SELECT incident_id = :ransom_id FROM fn_similar_incidents(:phish_id, 1, 0)),
    'S1 nearest neighbour is the close vector');
SELECT pg_temp.check(
    NOT EXISTS (SELECT 1 FROM fn_similar_incidents(:phish_id, 5, 0.9) WHERE incident_id = :scan_id),
    'S2 similarity threshold filters out the unrelated incident');
SELECT pg_temp.expect_error(
    format($$INSERT INTO incident_embeddings (incident_id, embedding, model_name, content_hash)
             VALUES (%s, '[1,2,3]', 'test', repeat('a', 64))$$, :scan_id),
    'S3 wrong vector dimension is rejected');

UPDATE incidents SET description = description || ' Source IP later seen in brute-force attempts.'
WHERE incident_id = :phish_id;
SELECT pg_temp.check(
    (SELECT is_stale FROM incident_embeddings WHERE incident_id = :phish_id),
    'S4 editing incident text marks its embedding stale');

\echo '--- Delete behaviour'
DELETE FROM incidents WHERE incident_id = :scan_id;
SELECT pg_temp.check(
    NOT EXISTS (SELECT 1 FROM incident_embeddings WHERE incident_id = :scan_id),
    'D1 deleting an incident cascades to its embedding');
SELECT pg_temp.expect_error(
    $$DELETE FROM users WHERE email = 't.admin@cirt.test'$$,
    'D2 a user who reported incidents cannot be deleted');

ROLLBACK;
